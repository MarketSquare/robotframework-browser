import tasks


def test_node_modules_left_in_wrapper_is_removed(tmp_path):
    (tmp_path / "node_modules" / "playwright-core").mkdir(parents=True)
    (tmp_path / "index.js").write_text("", encoding="utf-8")

    tasks._remove_shadowing_node_modules(tmp_path)

    assert not (tmp_path / "node_modules").exists()
    assert (tmp_path / "index.js").exists()


def test_wrapper_without_node_modules_is_left_alone(tmp_path):
    tasks._remove_shadowing_node_modules(tmp_path)

    assert list(tmp_path.iterdir()) == []
